"""Госномер автомобиля — приведение к читаемому виду.

В Узбекистане в ходу несколько форматов, и перечислять их по одному плохо:
любой не учтённый (прицеп, мотоцикл, спецтехника, дипломатический) остался бы
слипшимся комком вроде «01123ABC».

Поэтому правило общее, а не список шаблонов:
  1) первые ДВЕ цифры — код региона (в Узбекистане он всегда двузначный,
     01…95), отделяем их;
  2) остальное режем там, где цифры сменяются буквами, и наоборот.

Что из этого получается:
  01A123AA   -> 01 A 123 AA     (легковой, буква + 3 цифры + 2 буквы)
  01123ABC   -> 01 123 ABC      (легковой, 3 цифры + 3 буквы)
  011234AB   -> 01 1234 AB      (прицеп)
  01AB1234   -> 01 AB 1234
Неизвестный формат не ломается: если двух цифр в начале нет, номер просто
разбивается по сменам «цифры/буквы», а нераспознанное остаётся как есть.
"""
import re

MAX = 32
_RUN = re.compile(r"\d+|[^\W\d_]+|[^\w\s]+", re.UNICODE)


def format_plate(value) -> str:
    """«  01a  123bc » -> «01 A 123 BC». Пустое остаётся пустым."""
    raw = "".join(str(value or "").split()).upper()
    if not raw:
        return ""
    head = ""
    # код региона: ровно две цифры в начале, но только если дальше что-то есть
    if len(raw) > 2 and raw[:2].isdigit():
        head, raw = raw[:2], raw[2:]
    parts = [head] if head else []
    parts += _RUN.findall(raw)
    return " ".join(p for p in parts if p)[:MAX]
