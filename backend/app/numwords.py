"""Сумма прописью по-русски — для печатных форм (накладная, счёт-фактура).

Без этого накладную нельзя подписывать: «сумма прописью» — обязательный
реквизит, и вписывать её от руки в напечатанный бланк никто не станет.

Тонкость русского счёта, из-за которой нельзя обойтись простой таблицей:
в разряде тысяч числительное ЖЕНСКОГО рода («одна тысяча», «две тысячи»),
а в остальных — мужского («один миллион», «два сума»). Поэтому род
передаётся в _under_thousand отдельным флагом.
"""

_ONES_M = ("", "один", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять")
_ONES_F = ("", "одна", "две", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять")
_TEENS = (
    "десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
    "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать",
)
_TENS = ("", "", "двадцать", "тридцать", "сорок", "пятьдесят", "шестьдесят",
         "семьдесят", "восемьдесят", "девяносто")
_HUNDREDS = ("", "сто", "двести", "триста", "четыреста", "пятьсот",
             "шестьсот", "семьсот", "восемьсот", "девятьсот")

# (единственное, 2-4, много) для каждого разряда
_SCALES = (
    (("", "", ""), False),                                  # единицы
    (("тысяча", "тысячи", "тысяч"), True),                  # женский род!
    (("миллион", "миллиона", "миллионов"), False),
    (("миллиард", "миллиарда", "миллиардов"), False),
    (("триллион", "триллиона", "триллионов"), False),
)


def plural(n: int, forms: tuple[str, str, str]) -> str:
    """Выбрать форму слова: 1 сум / 2 сума / 5 сумов."""
    n = abs(n) % 100
    if 11 <= n <= 19:
        return forms[2]
    n %= 10
    if n == 1:
        return forms[0]
    if 2 <= n <= 4:
        return forms[1]
    return forms[2]


def _under_thousand(n: int, female: bool) -> list[str]:
    out: list[str] = []
    if n >= 100:
        out.append(_HUNDREDS[n // 100])
        n %= 100
    if 10 <= n <= 19:
        out.append(_TEENS[n - 10])
        return out
    if n >= 20:
        out.append(_TENS[n // 10])
        n %= 10
    if n:
        out.append((_ONES_F if female else _ONES_M)[n])
    return out


def int_to_words(n: int) -> str:
    """123 -> «сто двадцать три». Ноль отдаётся как «ноль»."""
    if n == 0:
        return "ноль"
    sign = "минус " if n < 0 else ""
    n = abs(n)
    groups: list[int] = []
    while n:
        groups.append(n % 1000)
        n //= 1000
    parts: list[str] = []
    for idx in range(len(groups) - 1, -1, -1):
        g = groups[idx]
        if not g:
            continue
        forms, female = _SCALES[idx] if idx < len(_SCALES) else _SCALES[-1]
        parts += _under_thousand(g, female)
        if forms[0]:
            parts.append(plural(g, forms))
    return sign + " ".join(p for p in parts if p)


def money_words(amount: float, tiyin: bool = True) -> str:
    """112000.5 -> «Сто двенадцать тысяч сум 50 тийин».

    «сум» и «тийин» НЕ склоняются. По правилам русского после «тысяч» шло бы
    «сумов», но в узбекских бланках (и в 1С:Узбекистан) валюта всегда пишется
    неизменяемой — «сто двенадцать тысяч сум». Разряды при этом склоняются
    как положено: одна тысяча / две тысячи / пять тысяч.

    Тийины печатаются ЦИФРАМИ: так их набирают в бланках и так короче.
    """
    neg = amount < 0
    cents = int(round(abs(float(amount or 0)) * 100))
    whole, frac = divmod(cents, 100)
    text = f"{int_to_words(whole)} сум"
    if tiyin:
        text += f" {frac:02d} тийин"
    return ("минус " if neg else "") + text[0].upper() + text[1:]
